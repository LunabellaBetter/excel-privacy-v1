class RestoreEngineError(Exception):
    """Base exception for Restore Engine failures. Must not expose secrets."""


@dataclass
class RestoreResult:
    """Detailed summary of restore operation."""

    run_id: str
    restored_workbook_path: Path
    restored_cells_count: int = 0
    skipped_conflicts_count: int = 0
    skipped_unconfirmed_count: int = 0
    total_protected_cells_count: int = 0
    restored_by_sheet: dict[str, int] = field(default_factory=dict)
    unresolved_by_sheet: dict[str, int] = field(default_factory=dict)
    change_list: ChangeList | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "run_id": self.run_id,
            "restored_workbook_path": str(self.restored_workbook_path),
            "restored_cells_count": self.restored_cells_count,
            "skipped_conflicts_count": self.skipped_conflicts_count,
            "skipped_unconfirmed_count": self.skipped_unconfirmed_count,
            "total_protected_cells_count": self.total_protected_cells_count,
            "restored_by_sheet": self.restored_by_sheet,
            "unresolved_by_sheet": self.unresolved_by_sheet,
            "change_list_summary": self.change_list.summary if self.change_list else {},
        }


def _make_record_key_tuple(record_identity_masked: list[dict[str, Any]] | None) -> tuple | None:
    if not record_identity_masked:
        return None
    components = []
    for item in record_identity_masked:
        f_name = item.get("field", "")
        f_val = str(item.get("value", "")).strip()
        components.append((f_name, f_val))
    return tuple(components)


@dataclass
class RestoreCoverage:
    """Read-only restore preflight, reconciled against every Ledger entry."""

    total_protected_cells_count: int = 0
    restorable_cells_count: int = 0
    conflict_cells_count: int = 0
    unconfirmed_cells_count: int = 0
    restorable_by_sheet: dict[str, int] = field(default_factory=dict)
    unresolved_by_sheet: dict[str, int] = field(default_factory=dict)
    unresolved_by_sheet_field: dict[str, dict[str, int]] = field(default_factory=dict)


@dataclass
class _RestorePlan:
    coverage: RestoreCoverage
    restores: list[tuple[Any, LedgerEntry]] = field(default_factory=list)


def _entry_field_label(entry: LedgerEntry) -> str:
    pf_id = entry.protected_field_id or ""
    if ":" in pf_id:
        return f"{pf_id.rsplit(':', 1)[-1]}｜{entry.logical_field}"
    return entry.logical_field


def _build_restore_plan(ledger: RecoveryLedger, change_list: ChangeList) -> _RestorePlan:
    """Resolve exactly which Ledger entries are safe to restore.

    The remainder is deliberately classified as unresolved, including protected
    cells in deleted/key-changed rows that do not have a CellChange entry.
    """
    entries_by_key: dict[tuple[str, str, tuple], LedgerEntry] = {}
    entries_by_masked_val: dict[tuple[str, str, str], list[LedgerEntry]] = {}
    entry_by_id = {id(entry): entry for entry in ledger.entries}

    for entry in ledger.entries:
        pf_id = entry.protected_field_id or entry.logical_field
        kt = _make_record_key_tuple(entry.record_identity_masked)
        if kt is not None:
            entries_by_key[(entry.sheet, pf_id, kt)] = entry
            entries_by_key[(entry.sheet, entry.logical_field, kt)] = entry
        masked = entry.get_decoded_masked_value()
        masked_str = str(masked).strip() if masked is not None else ""
        entries_by_masked_val.setdefault((entry.sheet, pf_id, masked_str), []).append(entry)
        if pf_id != entry.logical_field:
            entries_by_masked_val.setdefault(
                (entry.sheet, entry.logical_field, masked_str), []
            ).append(entry)

    def locate(change: Any) -> LedgerEntry | None:
        pf_id = change.protected_field_id or change.logical_field
        record_key = change.record_key if isinstance(change.record_key, tuple) else None
        entry = None
        if record_key is not None:
            entry = entries_by_key.get((change.sheet, pf_id, record_key))
            if entry is None and change.protected_field_id:
                entry = entries_by_key.get((change.sheet, change.logical_field, record_key))
        if entry is None:
            before = str(change.before_value).strip() if change.before_value is not None else ""
            candidates = entries_by_masked_val.get((change.sheet, pf_id, before), [])
            if not candidates and change.protected_field_id:
                candidates = entries_by_masked_val.get(
                    (change.sheet, change.logical_field, before), []
                )
            if len(candidates) == 1:
                entry = candidates[0]
        return entry

    conflict_ids: set[int] = set()
    for change in change_list.cell_changes:
        if change.status in (
            ChangeStatus.PROTECTED_VALUE_CONFLICT,
            ChangeStatus.RECORD_IDENTITY_CONFLICT,
        ):
            entry = locate(change)
            if entry is not None:
                conflict_ids.add(id(entry))

    restore_by_id: dict[int, tuple[Any, LedgerEntry]] = {}
    for change in change_list.cell_changes:
        if change.status != ChangeStatus.UNCHANGED:
            continue
        entry = locate(change)
        if entry is not None and id(entry) not in conflict_ids:
            restore_by_id.setdefault(id(entry), (change, entry))

    unresolved_ids = set(entry_by_id) - set(restore_by_id) - conflict_ids
    coverage = RestoreCoverage(
        total_protected_cells_count=len(ledger.entries),
        restorable_cells_count=len(restore_by_id),
        conflict_cells_count=len(conflict_ids),
        unconfirmed_cells_count=len(unresolved_ids),
    )
    for entry_id in restore_by_id:
        entry = entry_by_id[entry_id]
        coverage.restorable_by_sheet[entry.sheet] = coverage.restorable_by_sheet.get(entry.sheet, 0) + 1
    for entry_id in unresolved_ids:
        entry = entry_by_id[entry_id]
        coverage.unresolved_by_sheet[entry.sheet] = coverage.unresolved_by_sheet.get(entry.sheet, 0) + 1
        by_field = coverage.unresolved_by_sheet_field.setdefault(entry.sheet, {})
        label = _entry_field_label(entry)
        by_field[label] = by_field.get(label, 0) + 1

    return _RestorePlan(coverage=coverage, restores=list(restore_by_id.values()))


def analyze_restore_coverage(ledger: RecoveryLedger, change_list: ChangeList) -> RestoreCoverage:
    """Return the same safety coverage that restore execution will enforce."""
    return _build_restore_plan(ledger, change_list).coverage


def restore_workbook_v1(
    returned_workbook_path: Path | str,
    ledger_path: Path | str,
    secret_key: Any,
    output_dir: Path | str | None = None,
    output_filename: str | None = None,
    change_list: ChangeList | None = None,
    allow_conflicts: bool = True,
) -> RestoreResult:
    """Execute canonical Checkpoint 6 AI round-trip point restore engine.

    Args:
        returned_workbook_path: Path to workbook returned by AI / Codex.
        ledger_path: Path to encrypted Recovery Ledger file.
        secret_key: Fernet key bytes, string, or Fernet instance.
        output_dir: Target output directory for restored workbook.
        output_filename: Optional explicit filename (if None, auto-generates safe collision-free name).
        change_list: Pre-computed ChangeList from compare_workbook_against_ledger (optional).
        allow_conflicts: If True (default), restore UNCHANGED cells while safely skipping
            all PROTECTED_VALUE_CONFLICT cells without raising error. If False and conflicts exist,
            raises RestoreEngineError.

    Returns:
        RestoreResult with counts and output path.
    """
    from privacy_handler.excel_privacy_tool import (
        assert_supported_workbook,
        check_not_overwrite_source,
        load_workbook_private,
        resolve_path,
        sanitize_workbook_metadata,
        save_workbook_checked,
    )

    resolved_wb_path = Path(returned_workbook_path).resolve()
    resolved_ledger_path = Path(ledger_path).resolve()
    assert_supported_workbook(resolved_wb_path, action_name="还原")

    # Load ledger
    ledger = load_encrypted_ledger(resolved_ledger_path, secret_key)
    run_id = ledger.run.run_id

    # ------------------------------------------------------------------
    # Pre-Gate: Run Identity Check (Fail-closed before modifying/saving)
    # ------------------------------------------------------------------
    from privacy_handler.identity import (
        compute_run_fingerprint,
        read_workbook_identity,
        TOKEN_SEARCH_REGEX,
    )

    expected_run_id = ledger.run.run_id
    expected_fp8 = compute_run_fingerprint(expected_run_id)

    # Identity, Compare, and Restore use the same in-memory file snapshot.
    wb = load_workbook_private(resolved_wb_path)
    wb_ident = read_workbook_identity(wb)
    wb_run_id = wb_ident.get("run_id")

    if wb_run_id is not None:
        if wb_run_id != expected_run_id:
            raise RestoreEngineError(
                f"RUN_IDENTITY_MISMATCH: Returned workbook run_id '{wb_run_id}' does not match ledger run_id '{expected_run_id}'"
            )
    else:
        # Conservative fallback: scan cells for single consistent FP8 token (MSK-[FP8]-[TOKEN8])
        found_fp8s: set[str] = set()
        wb_temp = wb
        try:
            for sname in wb_temp.sheetnames:
                ws_temp = wb_temp[sname]
                for row in ws_temp.iter_rows(values_only=True):
                    for val in row:
                        if val and isinstance(val, str):
                            m = TOKEN_SEARCH_REGEX.search(val)
                            if m:
                                found_fp8s.add(m.group(1).upper())
        finally:
            if hasattr(wb_temp, "close"):
                wb_temp.close()

        if len(found_fp8s) == 0:
            # Pure numeric masking workbook or custom properties stripped without token clue
            raise RestoreEngineError(
                "RUN_IDENTITY_UNVERIFIED: Missing XPT_RunId and no text tokens available for fallback verification"
            )
        elif len(found_fp8s) > 1:
            raise RestoreEngineError(
                f"RUN_IDENTITY_UNVERIFIED: Multiple distinct token FP8 fingerprints found: {sorted(found_fp8s)}"
            )
        else:
            token_fp8 = next(iter(found_fp8s))
            if token_fp8 != expected_fp8:
                raise RestoreEngineError(
                    f"RUN_IDENTITY_MISMATCH: Token FP8 '{token_fp8}' does not match ledger FP8 '{expected_fp8}'"
                )

    # If ChangeList is not provided, run comparison engine
    # A GUI preview is advisory: the file may have changed after Compare.
    # Never use an externally supplied/stale plan as authority to write PII.
    change_list = compare_workbook_against_ledger(
        returned_workbook_or_path=wb,
        ledger_or_path=resolved_ledger_path,
        secret_key=secret_key,
    )

    if not allow_conflicts and change_list.has_conflicts:
        raise RestoreEngineError(
            f"Cannot restore workbook due to conflicts: {change_list.summary}"
        )

    restore_plan = _build_restore_plan(ledger, change_list)
    coverage = restore_plan.coverage

    # Load returned workbook into memory
    # wb was loaded once above; do not reopen a potentially changed input.

    restored_cells_count = 0
    skipped_conflicts_count = coverage.conflict_cells_count
    skipped_unconfirmed_count = coverage.unconfirmed_cells_count
    restored_by_sheet: dict[str, int] = {}

    # Process only preflight-confirmed Ledger entries. The plan applies the same
    # Record Identity / physical protected-field / masked-value gates as Compare.
    for change, target_entry in restore_plan.restores:
        sheet_name = change.sheet
        row_idx = change.row_idx
        col_idx = change.col_idx

        if sheet_name not in wb.sheetnames or row_idx is None or col_idx is None:
            continue

        ws = wb[sheet_name]

        # Restore typed original value
        orig_val = target_entry.get_decoded_original_value()
        cell = ws.cell(row=row_idx, column=col_idx)
        cell.value = orig_val

        restored_cells_count += 1
        restored_by_sheet[sheet_name] = restored_by_sheet.get(sheet_name, 0) + 1

    # Recalculation & metadata hygiene
    ensure_workbook_recalculation_properties(wb)
    sanitize_workbook_metadata(wb)

    # Determine safe output path
    resolved_out_dir = Path(output_dir).resolve() if output_dir else resolve_path("restored_outputs")
    resolved_out_dir.mkdir(parents=True, exist_ok=True)

    output_suffix = ".restored.xlsx"
    if output_filename:
        restored_path = resolved_out_dir / output_filename
    else:
        restored_path = resolve_safe_output_path(resolved_out_dir, resolved_wb_path, suffix=output_suffix)

    check_not_overwrite_source(restored_path, resolved_wb_path)
    save_workbook_checked(wb, restored_path)

    return RestoreResult(
        run_id=run_id,
        restored_workbook_path=restored_path,
        restored_cells_count=restored_cells_count,
        skipped_conflicts_count=skipped_conflicts_count,
        skipped_unconfirmed_count=skipped_unconfirmed_count,
        total_protected_cells_count=coverage.total_protected_cells_count,
        restored_by_sheet=restored_by_sheet,
        unresolved_by_sheet=coverage.unresolved_by_sheet,
        change_list=change_list,
    )
