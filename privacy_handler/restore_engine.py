"""AI Round-trip Point Restore Engine for V1 privacy protocol.

Restores an AI-returned workbook back to its original typed values using an encrypted Recovery Ledger.
Consumes ChangeList generated by compare_workbook_against_ledger (or executes compare internally).

Core Invariants:
1. Typed Value Restoration: Original types (str, int, float, bool, date, datetime, leading zero text)
   are restored faithfully to openpyxl cell values.
2. Numeric Restore Iron Law:
   Only restore original typed value if:
   - Record Identity matches
   - Logical Field matches
   - Expected Masked Value matches (UNCHANGED cell status)
   If cell was modified, swapped, or moved (PROTECTED_VALUE_CONFLICT), NEVER overwrite.
   NEVER perform inverse arithmetic (e.g. dividing AI returned amount by scale factor k).
3. Text Token Restoration:
   Restored only when cell status is UNCHANGED. Swapped or alien tokens are never overwritten.
4. Structural Preservation:
   AI row re-ordering (whole-row sorts) is naturally preserved because cells are restored by matched coordinates.
   AI inserted columns, non-protected column edits, formulas, and extra sheets remain intact.
   Deleted rows remain absent; added rows remain added with zero PII injected.
5. Recalculation & Metadata Hygiene:
   Applies fullCalcOnLoad and forceFullCalc so formulas referencing restored values update automatically upon opening.
6. Diagnostic Privacy:
   Logs, summaries, and safe exports contain ephemeral aliases (e.g. Record-01) and never leak plaintext PII.
"""

